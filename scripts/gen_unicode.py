#!/usr/bin/env python3
"""Generate galdr/unicode_tables.odin (and its conformance test) from the UCD.

usage: scripts/gen_unicode.py [UCD_DIR]
UCD_DIR holds these files from https://www.unicode.org/Public/<ver>/ucd/:
  EastAsianWidth.txt, extracted/DerivedGeneralCategory.txt,
  auxiliary/GraphemeBreakProperty.txt, auxiliary/GraphemeBreakTest.txt,
  emoji/emoji-data.txt, DerivedCoreProperties.txt  (flattened into one directory)
Missing files are downloaded into UCD_DIR.
"""
import os, re, sys, urllib.request

VERSION = '16.0.0'
BASE = f'https://www.unicode.org/Public/{VERSION}/ucd/'
FILES = {
    'EastAsianWidth.txt': 'EastAsianWidth.txt',
    'DerivedGeneralCategory.txt': 'extracted/DerivedGeneralCategory.txt',
    'GraphemeBreakProperty.txt': 'auxiliary/GraphemeBreakProperty.txt',
    'GraphemeBreakTest.txt': 'auxiliary/GraphemeBreakTest.txt',
    'emoji-data.txt': 'emoji/emoji-data.txt',
    'DerivedCoreProperties.txt': 'DerivedCoreProperties.txt',
}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ucd = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '.ucd')
os.makedirs(ucd, exist_ok=True)
for name, rel in FILES.items():
    path = os.path.join(ucd, name)
    if not os.path.exists(path):
        print('downloading', rel)
        urllib.request.urlretrieve(BASE + rel, path)

LINE = re.compile(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^#]+?)\s*(?:#.*)?$')

def parse(name, field=0):
    """Yield (lo, hi, values...) for each data line."""
    for line in open(os.path.join(ucd, name), encoding='utf-8'):
        line = line.strip()
        if not line or line.startswith('#'): continue
        m = LINE.match(line)
        if not m: continue
        lo = int(m.group(1), 16); hi = int(m.group(2) or m.group(1), 16)
        yield lo, hi, [v.strip() for v in m.group(3).split(';')]

def merge(ranges):
    """Merge sorted (lo, hi, val) ranges that touch and share a value."""
    out = []
    for lo, hi, v in sorted(ranges):
        if out and out[-1][2] == v and out[-1][1] + 1 >= lo:
            out[-1] = (out[-1][0], max(out[-1][1], hi), v)
        else:
            out.append((lo, hi, v))
    return out

# --- widths -----------------------------------------------------------------
wide = [(lo, hi, 1) for lo, hi, v in parse('EastAsianWidth.txt') if v[0] in ('W', 'F')]
# Regional indicators are Emoji_Presentation but wcwidth terminals draw each
# half of a flag one cell wide; cluster mode sizes the pair as 2 separately.
emoji_pres = [(lo, hi, 1) for lo, hi, v in parse('emoji-data.txt')
              if v[0] == 'Emoji_Presentation' and not (lo >= 0x1F1E6 and hi <= 0x1F1FF)]
wide = merge(wide + emoji_pres)

zero_cats = {'Mn', 'Me', 'Cf'}
zero = [(lo, hi, 1) for lo, hi, v in parse('DerivedGeneralCategory.txt') if v[0] in zero_cats]
zero += [(0x1160, 0x11FF, 1),   # Hangul medial vowels / final consonants: combine with the lead
         (0xD7B0, 0xD7FF, 1)]
# U+00AD SOFT HYPHEN is Cf but terminals draw it one cell wide.
zero = [(lo, hi, v) for lo, hi, v in zero if not (lo <= 0xAD <= hi)] + \
       [(lo, hi, 1) for lo, hi, v in parse('DerivedGeneralCategory.txt') if v[0] == 'Cf' and lo <= 0xAD <= hi and lo != 0xAD]
zero = merge(zero)

# --- grapheme break -------------------------------------------------------------
GBP = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend',
       'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
gbp = merge([(lo, hi, GBP.index(v[0])) for lo, hi, v in parse('GraphemeBreakProperty.txt')])
extpict = merge([(lo, hi, 1) for lo, hi, v in parse('emoji-data.txt') if v[0] == 'Extended_Pictographic'])
INCB = ['None', 'Linker', 'Consonant', 'Extend']
incb = merge([(lo, hi, INCB.index(v[1])) for lo, hi, v in parse('DerivedCoreProperties.txt')
              if v[0] == 'InCB'])

def table(name, rows, with_value):
    body = []
    for lo, hi, v in rows:
        body.append(f'\t{{0x{lo:X}, 0x{hi:X}, {v}}},' if with_value else f'\t{{0x{lo:X}, 0x{hi:X}}},')
    kind = '[3]u32' if with_value else '[2]u32'
    return f'@(private, rodata)\n{name} := [?]{kind}{{\n' + '\n'.join(body) + '\n}\n'

out = [f'''package galdr

// GENERATED by scripts/gen_unicode.py from Unicode {VERSION}. Do not edit.

UNICODE_VERSION :: "{VERSION}"

Grapheme_Break :: enum u8 {{
{chr(10).join(f"	{n}," for n in GBP)}
}}

InCB :: enum u8 {{
{chr(10).join(f"	{n}," for n in INCB)}
}}
''',
    table('_WIDE', [(lo, hi, 0) for lo, hi, _ in wide], False),
    table('_ZERO', [(lo, hi, 0) for lo, hi, _ in zero], False),
    table('_GBP', gbp, True),
    table('_EXTPICT', [(lo, hi, 0) for lo, hi, _ in extpict], False),
    table('_INCB', incb, True),
]
path = os.path.join(ROOT, 'galdr', 'unicode_tables.odin')
open(path, 'w').write('\n'.join(out))
print(f'wrote {path}: wide={len(wide)} zero={len(zero)} gbp={len(gbp)} extpict={len(extpict)} incb={len(incb)}')

# --- conformance test -----------------------------------------------------------
cases = []
for line in open(os.path.join(ucd, 'GraphemeBreakTest.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line: continue
    tokens = line.split()
    # tokens alternate: ÷|× then hex codepoint
    clusters, cur = [], []
    for tok in tokens[1:]:
        if tok in ('÷', '×'):
            if tok == '÷':
                clusters.append(cur); cur = []
        else:
            cur.append(int(tok, 16))
    if any(0xD800 <= c <= 0xDFFF for cl in clusters for c in cl):
        continue  # surrogates can't appear in UTF-8
    cases.append(clusters)

def lit(cps):
    return '"' + ''.join(f'\\U{c:08x}' for c in cps) + '"'

test = [f'''package galdr

// GENERATED by scripts/gen_unicode.py from GraphemeBreakTest-{VERSION}.txt. Do not edit.

import "core:testing"

@(private = "file")
GRAPHEME_CASES := [?][]string{{
''']
for clusters in cases:
    test.append('\t{' + ', '.join(lit(c) for c in clusters) + '},\n')
test.append('''}

@(test)
test_grapheme_conformance :: proc(t: ^testing.T) {
	failed := 0
	for expected, n in GRAPHEME_CASES {
		joined := ""
		for c in expected do joined = _concat(joined, c)
		i, k := 0, 0
		ok := true
		for i < len(joined) {
			end := grapheme_end(joined, i)
			if k >= len(expected) || joined[i:end] != expected[k] {
				ok = false
				break
			}
			i = end
			k += 1
		}
		if !ok || k != len(expected) {
			failed += 1
			if failed <= 5 do testing.expectf(t, false, "grapheme case %d segmented wrongly: %q", n, joined)
		}
	}
	testing.expectf(t, failed == 0, "%d of %d UAX #29 conformance cases failed", failed, len(GRAPHEME_CASES))
}
''')
tpath = os.path.join(ROOT, 'galdr', 'unicode_conformance_test.odin')
open(tpath, 'w').write(''.join(test))
print(f'wrote {tpath}: {len(cases)} cases')
